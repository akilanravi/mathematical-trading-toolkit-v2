import json
from pathlib import Path
from datetime import datetime
from zoneinfo import ZoneInfo
import pandas as pd
import streamlit as st
from db import save_desk,rows
from fiidii import fetch

def render(provider):
 st.subheader('Next-Day Institutional Desk')
 st.caption('After-close snapshots are generated by GitHub Actions at 15:55 IST on weekdays; runs may be delayed. These are watchlist snapshots, not ranked F&O candidates.')
 files=sorted(Path('desk_snapshots').glob('*.json'),reverse=True) if Path('desk_snapshots').exists() else []
 if files:
  f=files[0]
  try:
   snapshot=json.loads(f.read_text(encoding='utf-8'))
   st.success(f"Latest saved snapshot: {snapshot.get('created_ist','N/A')}")
   st.dataframe(pd.DataFrame.from_dict(snapshot.get('watchlist',{}),orient='index'),use_container_width=True)
   st.dataframe(pd.DataFrame.from_dict(snapshot.get('indices',{}),orient='index'),use_container_width=True)
   if snapshot.get('fiidii'):st.write('FII/DII:',snapshot['fiidii'])
  except Exception as exc:st.error('Snapshot cannot be read: '+str(exc))
 else:st.info('No after-close snapshot yet. Run the GitHub Actions workflow manually or wait for its scheduled run.')
 st.warning('A full next-day Top 10 F&O ranking requires verified instrument master, intraday candles and derivatives metrics. Unavailable fields are not fabricated.')
